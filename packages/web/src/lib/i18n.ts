export const dictionaries = { ko, en } as const;

/** Placeholder names in a Korean string, so `t` can require exactly the variables it needs. */
type PlaceholderOf<S extends string> = S extends `${string}{${infer P}}${infer Rest}` ? (P extends `${infer N}|${string}` ? N : P) | PlaceholderOf<Rest> : never;
type Vars<K extends Key> = Record<PlaceholderOf<(typeof ko)[K]>, string | number>;
type Args<K extends Key> = [PlaceholderOf<(typeof ko)[K]>] extends [never] ? [] : [vars: Vars<K>];

const PLACEHOLDER = /\{(\w+)(?:\|([^|}]*)\|([^}]*))?\}/g;
const table: Record<Key, string> = lang === 'en' ? en : ko;

/** Fills `{name}` and `{name|one|other}` from `vars`; unknown names are left as they are. */
export function fill(text: string, vars?: Record<string, string | number>): string {
  if (!vars) return text;
  return text.replace(PLACEHOLDER, (whole, name: string, one: string | undefined, other: string | undefined) => {
    if (!(name in vars)) return whole;
    const v = vars[name];
    return one === undefined ? String(v) : Number(v) === 1 ? one : (other ?? one);
  });
}

export function t<K extends Key>(key: K, ...args: Args<K>): string {
  return fill(table[key], args[0] as Record<string, string | number> | undefined);
}
