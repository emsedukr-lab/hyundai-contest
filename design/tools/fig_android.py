"""Generate Android resource XML from extracted Pleos tokens.

Usage: python fig_android.py <tokens_dir> <res_out_dir> [form_factor=connect-s]

Writes:
  values/pleos_colors.xml        (Light)
  values-night/pleos_colors.xml  (Dark)
  values/pleos_dimens.xml        (form_factor + Number tokens, dp)
  values/pleos_type.xml          (TextAppearance.Pleos.* from text styles, sp)
"""
import json
import os
import re
import sys
from xml.sax.saxutils import escape

COLOR_SETS = ["Color (COLOR)", "[Theme] ◑ Color (COLOR)", "Primitives (COLOR)"]
DIMEN_SETS = ["form_factor (FLOAT)", "form_factor_common (FLOAT)", "typo (FLOAT)", "Typo (FLOAT)", "Number (FLOAT)"]
WEIGHTS = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700, "ExtraBold": 800}


def res_name(prefix, name):
    s = re.sub(r"[^a-z0-9]+", "_", name.strip().lower()).strip("_")
    return f"{prefix}_{s}"


def android_color(hex_):
    return hex_  # Figma #AARRGGBB already matches Android ordering


def write(path, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fp:
        fp.write('<?xml version="1.0" encoding="utf-8"?>\n')
        fp.write("<!-- Generated by design/tools/fig_android.py from Pleos Connect .fig files. Do not edit. -->\n")
        fp.write("<resources>\n" + body + "</resources>\n")


def colors(variables, res):
    light, dark, seen = [], [], set()
    for set_name in COLOR_SETS:
        for name, modes in variables.get(set_name, {}).items():
            if name.startswith("_") or not modes:
                continue
            key = res_name("pleos", name)
            if key in seen:
                continue
            l = modes.get("Light") or next(iter(modes.values()))
            d = modes.get("Dark") or l
            if not l:
                continue
            seen.add(key)
            light.append(f'    <color name="{key}">{android_color(l)}</color>  <!-- {escape(name)} -->\n')
            dark.append(f'    <color name="{key}">{android_color(d or l)}</color>\n')
    write(f"{res}/values/pleos_colors.xml", "".join(light))
    write(f"{res}/values-night/pleos_colors.xml", "".join(dark))
    return len(seen)


def dimens(variables, res, ff):
    out, seen = [], set()
    for set_name in DIMEN_SETS:
        for name, modes in variables.get(set_name, {}).items():
            if name.startswith("_") or not modes:
                continue
            v = modes.get(ff, modes.get("\b" + ff, modes.get("connect", modes.get("Mode 1"))))
            if v is None:
                continue
            key = res_name("pleos", name)
            if key in seen:
                continue
            seen.add(key)
            out.append(f'    <dimen name="{key}">{v}dp</dimen>  <!-- {escape(name)} -->\n')
    write(f"{res}/values/pleos_dimens.xml", "".join(out))
    return len(seen)


def type_styles(tokens_dir, res):
    styles = {}
    for f in ("styles_assets.json", "styles_display.json"):
        for name, s in json.load(open(os.path.join(tokens_dir, f)))["text"].items():
            if s["font"] != "Asta Sans":  # Pleos system font only; skip doc/brand-internal fonts
                continue
            styles.setdefault(name, s)
    out = []
    for name, s in sorted(styles.items()):
        style = "TextAppearance.Pleos." + re.sub(r"[^A-Za-z0-9]+", ".", name).strip(".")
        size = int(s["size"])
        lh = float(s["lineHeight"]) if s["lineHeight"] and not s["lineHeight"].endswith("%") else None
        out.append(f'    <style name="{style}">\n')
        out.append('        <item name="android:fontFamily">@font/asta_sans</item>\n')
        out.append(f'        <item name="android:textSize">{size}sp</item>\n')
        out.append(f'        <item name="android:textFontWeight">{WEIGHTS.get(s["weight"], 400)}</item>\n')
        if lh:
            out.append(f'        <item name="lineHeight">{int(lh)}sp</item>\n')
        out.append("    </style>\n")
    write(f"{res}/values/pleos_type.xml", "".join(out))
    return len(styles)


def main():
    tokens_dir, res = sys.argv[1], sys.argv[2]
    ff = sys.argv[3] if len(sys.argv) > 3 else "connect-s"
    variables = json.load(open(os.path.join(tokens_dir, "variables.json")))
    print("colors", colors(variables, res))
    print("dimens", dimens(variables, res, ff))
    print("text styles", type_styles(tokens_dir, res))


if __name__ == "__main__":
    main()
